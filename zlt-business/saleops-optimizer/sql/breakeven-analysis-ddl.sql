  `last_recalculation` datetime DEFAULT NULL COMMENT '最后重算时间',
  `forecast_model` varchar(64) DEFAULT NULL COMMENT '使用的预测模型',
  `forecast_confidence` decimal(3,2) DEFAULT NULL COMMENT '预测置信度',
  `seasonal_factors` longtext COMMENT '季节性因子(JSON)',
