-- 创建视图：分析概览
CREATE OR REPLACE VIEW `v_breakeven_analysis_overview` AS
SELECT 
    ba.analysis_id,
    ba.analysis_name,
    ba.analysis_type,
    ba.analysis_period,
    ba.tenant_id,
    ba.creator_name,
    ba.breakeven_point,
    ba.margin_safety_ratio,
    ba.reasonability_score,
    ba.status,
    ba.created_at,
    ba.last_recalculation,
    COUNT(bs.id) as scenario_count,
    COUNT(bse.id) as sensitivity_count,
    COUNT(bf.id) as forecast_count
FROM soo_breakeven_analysis ba
LEFT JOIN soo_breakeven_scenarios bs ON ba.analysis_id = bs.analysis_id AND bs.status = 'active'
LEFT JOIN soo_breakeven_sensitivity bse ON ba.analysis_id = bse.analysis_id
LEFT JOIN soo_breakeven_forecast bf ON ba.analysis_id = bf.analysis_id AND bf.forecast_status = 'ready'
WHERE ba.status = 'active'
GROUP BY ba.analysis_id, ba.analysis_name, ba.analysis_type, ba.analysis_period, 
         ba.tenant_id, ba.creator_name, ba.breakeven_point, ba.margin_safety_ratio, 
         ba.reasonability_score, ba.status, ba.created_at, ba.last_recalculation; 